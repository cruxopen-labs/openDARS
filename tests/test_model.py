from dataclasses import replace
import json
import numpy as np
import pytest
from dars.hardware import BASE, Hardware, ppa
from dars.performance import Performance, Mapping, aggregate, features, samples
from dars.workload import config, workload, Op


@pytest.fixture(scope="module")
def perf():
    return Performance().fit()


def test_measured_cycle_accounting():
    for item in samples():
        sample = item["sample"]
        if sample.get("operators"):
            assert sum(o["cycles"] for o in sample["operators"]) == sample["cycles"]
        assert len(workload(config(item["model"]), **item["kwargs"])) == sample["descriptors"]


def test_fit_holdout_and_repeat(perf):
    rows = perf.validate()
    # Regression gate against independent preserved FPGA measurements, not
    # expected values generated by our analytical equations.
    assert max(abs(r["error_pct"]) for r in rows) < 10
    assert max(abs(v) for r in rows if r["train"] for v in r["class_error_pct"].values()) < 10
    assert sum(r["model"] == "gemma3" for r in rows) == 6
    assert not any(r["train"] for r in rows if r["model"] == "gemma3" or "repeat" in r["dataset"])
    assert all(np.isfinite(v) and v >= 0 for coefs in perf.coefficients.values() for v in coefs)


def test_aggregation_matches_each_descriptor():
    ops = workload(config("qwen3.5"), "prefill", tokens=5)
    a = aggregate(ops)
    single = {k: np.zeros(6) for k in a}
    for op in ops:
        for kind, value in aggregate([op]).items():
            single[kind] += value
    for k in a:
        np.testing.assert_allclose(a[k], single[k])


def test_hardware_and_mapping_paths(perf):
    c = config("qwen3.5")
    ops = workload(c, "prefill", tokens=20)
    base = perf.predict(ops)["cycles"]
    assert perf.predict(ops, replace(BASE, vpu_lanes=8))["cycles"] < base
    assert perf.predict(ops, replace(BASE, read_gbs=2))["cycles"] > base
    assert perf.predict(ops, mapping=Mapping(fusion=True), c=c)["cycles"] <= base
    resident = Mapping(delta_block=True)
    assert perf.predict(ops, mapping=resident, c=c)["cycles"] == base  # 4KiB cannot hold a tile
    larger = replace(BASE, hold_kib=80)
    assert perf.predict(ops, larger, resident, c)["cycles"] != perf.predict(ops, larger)["cycles"]
    assert len(workload(c, "prefill", tokens=20, skip_head=True)) < len(ops)
    # GQA only changes reads; no arithmetic reduction.
    fa = config("qwen3")
    dots = workload(fa, position=250)
    no_reuse = aggregate(dots, replace(BASE, fdot_lanes=32), c=fa)
    reuse = aggregate(dots, replace(BASE, fdot_lanes=32), Mapping(gqa_reuse=True), fa)
    assert reuse["fdot_nn"][1] <= no_reuse["fdot_nn"][1]
    small = replace(BASE, gemv_bytes=16)
    with_mxu = replace(small, mxu_rows=4, mxu_cols=32)
    assert features(Op(2, 4, 1024, 1024), with_mxu)[1] < features(Op(2, 4, 1024, 1024), small)[1]


def test_ppa_observation_anchors():
    r = ppa(BASE)
    assert (r["lut"], r["dsp"], r["bram"]) == (104879, 903, 118)
    assert r["power_w"] == pytest.approx(4.443)
    assert r["feasible"]
    assert not ppa(replace(BASE, mxu_rows=16, mxu_cols=16))["feasible"]
    assert "UNCALIBRATED" in ppa(BASE, "asic")["status"]
    with pytest.raises(ValueError):
        Hardware(mxu_rows=8)
    with pytest.raises(ValueError):
        Hardware(read_gbs=float("nan"))
    with pytest.raises(ValueError):
        Hardware(fdot_lanes=3.5)
